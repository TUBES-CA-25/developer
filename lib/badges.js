/**
 * Get badge info for a technology string
 */
export function getTechBadge(techName) {
  if (!techName) return null;
  const key = techName.toLowerCase().trim();
  const url = TECH_BADGES[key];
  if (url) {
    return { name: techName, badgeUrl: url };
  }

  // Fallback pattern matching
  for (const [pattern, badgeUrl] of Object.entries(TECH_BADGES)) {
    if (key.includes(pattern) || pattern.includes(key)) {
      return { name: techName, badgeUrl };
    }
  }

  // Generic fallback badge
  const safeName = encodeURIComponent(techName.replace(/-/g, "--").replace(/_/g, "__").replace(/ /g, "_"));
  return {
    name: techName,
    badgeUrl: `https://img.shields.io/badge/${safeName}-2D3748?style=for-the-badge`,
  };
}
